"""Generate and validate the gzip C header embedded in the firmware."""
import argparse
import gzip
import io
import re
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def render_header(data):
    rows = [', '.join(f'0x{byte:02x}' for byte in data[i:i + 12]) for i in range(0, len(data), 12)]
    return ('/* Generated by tools/embed_page.py. */\n#ifndef PAGE_INDEX_H\n#define PAGE_INDEX_H\n'
            'static const unsigned char page_index[] = {\n    ' + ',\n    '.join(rows) +
            '\n};\nstatic const unsigned int page_index_len = sizeof(page_index);\n#endif\n')


def matches_source(header, source):
    # zlib and zlib-ng can encode identical HTML with different DEFLATE bytes.
    # Validate the C wrapper and gzip integrity, then compare the actual page.
    data = bytes(int(byte, 16) for byte in re.findall(r'0x([0-9a-f]{2})', header))
    if render_header(data) != header:
        return False
    try:
        return gzip.decompress(data) == source
    except (OSError, EOFError, zlib.error):
        return False


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'components/webserver/pages/page_index.h')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = (ROOT / 'web/dist/index.html').read_text(encoding='utf-8').encode('utf-8')
    if args.check:
        if not args.output.exists() or not matches_source(args.output.read_text(encoding='utf-8'), source):
            raise SystemExit('Embedded UI is stale or corrupt. Run: python tools/embed_page.py')
    else:
        compressed = io.BytesIO()
        with gzip.GzipFile(filename='', fileobj=compressed, mode='wb', mtime=0) as stream:
            stream.write(source)
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(render_header(compressed.getvalue()), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
