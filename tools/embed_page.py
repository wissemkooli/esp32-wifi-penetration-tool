"""Generate the deterministic gzip C header embedded in the firmware."""
import argparse
import gzip
import io
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output', type=Path, default=ROOT / 'components/webserver/pages/page_index.h')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = (ROOT / 'web/dist/index.html').read_text(encoding='utf-8').encode('utf-8')
compressed = io.BytesIO()
with gzip.GzipFile(filename='', fileobj=compressed, mode='wb', mtime=0) as stream:
    stream.write(source)
data = compressed.getvalue()
rows = [', '.join(f'0x{byte:02x}' for byte in data[i:i + 12]) for i in range(0, len(data), 12)]
text = ('/* Generated by tools/embed_page.py. */\n#ifndef PAGE_INDEX_H\n#define PAGE_INDEX_H\n'
        'static const unsigned char page_index[] = {\n    ' + ',\n    '.join(rows) +
        '\n};\nstatic const unsigned int page_index_len = sizeof(page_index);\n#endif\n')
if args.check:
    if not args.output.exists() or args.output.read_text() != text:
        raise SystemExit('Embedded UI is stale. Run: python tools/embed_page.py')
else:
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, newline='\n')
